-- Hand-written Postgres DDL for Report (see workspace.sql for why).
-- Same columns as fadymondy.com-v2's Report (its togo.resources.yaml), plus
-- workspace_id and project_id. Keys are MG-<number>, numbered per workspace
-- (internal/reports/number.go); the server allocates, never the client.
CREATE TABLE IF NOT EXISTS reports (
    id              text PRIMARY KEY DEFAULT gen_random_uuid()::text,
    workspace_id    text        NOT NULL,
    project_id      text,
    number          bigint      NOT NULL,
    key             text        NOT NULL,
    title           text        NOT NULL,
    body            text,
    issue_type      text        NOT NULL DEFAULT 'bug',
    status          text        NOT NULL DEFAULT 'backlog',
    state           text        NOT NULL DEFAULT 'open',
    resolution      text,
    priority        text        NOT NULL DEFAULT 'medium',
    labels          text,
    assignee_id     text,
    reporter_id     text,
    parent_id       text,
    milestone       text,
    external_source text,
    external_id     text,
    external_key    text,
    external_url    text,
    page_url        text,
    route           text,
    selector        text,
    screenshot      text,
    console_log     text,
    network_log     text,
    user_agent      text,
    viewport        text,
    closed_at       timestamptz,
    sort_order      bigint      NOT NULL DEFAULT 0,
    started_at      timestamptz,
    finished_at     timestamptz,
    agent_seconds   bigint      NOT NULL DEFAULT 0,
    agent_session   text,
    human_only      boolean     NOT NULL DEFAULT false,
    ai_model        text,
    ai_effort       text,
    agent           text,
    skill           text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, number),
    UNIQUE (workspace_id, key)
);
