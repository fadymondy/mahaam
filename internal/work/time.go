// EntryFilter narrows ListTimeEntries. Dates are workspace-local and inclusive.
type EntryFilter struct {
	User      string // "" = you; a user id = that member (time:manage); "*" = everyone (time:manage)
	From, To  string
	ProjectID string
	Limit     int
}

// ListTimeEntries lists entries overlapping [From, To], newest first (default: the last 7 days).
func (sv *Service) ListTimeEntries(ctx context.Context, f EntryFilter) ([]TimeEntry, error) {
	s, err := caller(ctx)
	if err != nil {
		return nil, err
	}
	if err := require(s, authz.TimeTrack); err != nil {
		return nil, err
	}
	conf, err := loadTimeConf(ctx, sv.DB, s.WorkspaceID)
	if err != nil {
		return nil, err
	}
	args := []any{s.WorkspaceID}
	where := "WHERE e.workspace_id = $1"
	switch strings.TrimSpace(f.User) {
	case "*":
		if err := require(s, authz.TimeManage); err != nil {
			return nil, err
		}
	default:
		who, err := sv.personFor(ctx, s, f.User)
		if err != nil {
			return nil, err
		}
		args = append(args, who)
		where += " AND e.user_id = $2"
	}
	n := time.Now().In(conf.Loc)
	today := time.Date(n.Year(), n.Month(), n.Day(), 0, 0, 0, 0, conf.Loc)
	from, err := localDay(f.From, conf.Loc)
	if err != nil {
		return nil, err
	}
	to, err := localDay(f.To, conf.Loc)
	if err != nil {
		return nil, err
	}
	if to == nil {
		to = &today
	}
	if from == nil {
		d := time.Date(to.Year(), to.Month(), to.Day()-6, 0, 0, 0, 0, conf.Loc)
		from = &d
	}
	if to.Before(*from) {
		return nil, invalid("from is after to")
	}
	until := time.Date(to.Year(), to.Month(), to.Day()+1, 0, 0, 0, 0, conf.Loc)
	args = append(args, until.UTC(), from.UTC())
	where += " AND e.started_at < $" + itoa(len(args)-1) + " AND (e.ended_at IS NULL OR e.ended_at > $" + itoa(len(args)) + ")"
	if ref := strings.TrimSpace(f.ProjectID); ref != "" {
		p, err := sv.FindProject(ctx, ref)
		if err != nil {
			return nil, err
		}
		args = append(args, p.ID)
		where += " AND e.project_id = $" + itoa(len(args))
	}
	limit := f.Limit
	if limit <= 0 || limit > 1000 {
		limit = 500
	}
	args = append(args, limit)
	rows, err := sv.DB.QueryContext(ctx, entrySelect+where+" ORDER BY e.started_at DESC LIMIT $"+itoa(len(args)), args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []TimeEntry{}
	for rows.Next() {
		e, err := scanEntry(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, *view(s, e))
	}
	return out, rows.Err()
}

func itoa(n int) string {
	if n < 10 {
		return string(rune('0' + n))
	}
	return itoa(n/10) + string(rune('0'+n%10))
}
